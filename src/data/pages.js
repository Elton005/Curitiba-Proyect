export function pageHref(page = "home", language = "pt", hash = "") {
  const definition = pages[page];
  if (!definition) throw new Error(`Unknown page: ${page}`);
  return `${language === "es" ? "/es/" : "/"}${definition.slug ? `${definition.slug}/` : ""}${hash ? `#${hash}` : ""}`;
}

export function resolvePage(pathname) {
  let path;
  try {
    path = decodeURIComponent(pathname);
  } catch {
    return { page: null, language: "pt" };
  }
  const language = /^\/es(?:\/|$)/.test(path) ? "es" : "pt";
  path = path
    .replace(/\/index\.html$/, "/")
    .replace(/^\/es(?=\/|$)/, "")
    .replace(/^\/+|\/+$/g, "");
  const page =
    Object.keys(pages).find((key) => pages[key].slug === path) || null;
  return { page, language };
}
